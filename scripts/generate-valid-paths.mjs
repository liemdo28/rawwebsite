#!/usr/bin/env node
/**
 * scripts/generate-valid-paths.mjs — Generates functions/_validPaths.mjs (a
 * build-time manifest of every real request path this site serves) and
 * functions/_notFoundPage.mjs (the literal 404 page body, inlined).
 *
 * Why this exists: Cloudflare Pages routes Functions (including
 * _middleware.js) ahead of static assets, and env.ASSETS.fetch() applies
 * the same "assume SPA, fall back to index.html" behavior as the top-level
 * request for any path with no matching asset when called *from inside a
 * Function* — confirmed live (2026-07-28) for BOTH existence-checking
 * (ASSETS.fetch(path).status was never 404) and content-fetching
 * (ASSETS.fetch('/404.html') returned 200 with the homepage's own HTML
 * body, not 404.html's content, even though public/404.html is a real
 * file). So _middleware.js can't reliably ask Cloudflare "does this path
 * exist" or "give me this static file" via ASSETS.fetch from inside a
 * Function at all — both the existence check and the 404 body must be
 * fully self-contained, with no dependency on that binding.
 * _middleware.js instead checks the request path against VALID_PATHS,
 * generated directly from the actual file listing in public/, and serves
 * NOT_FOUND_HTML, generated directly from public/404.html's own content.
 * Because VALID_PATHS reflects only files that really exist in public/, a
 * not-yet-published campaign article (no public/{slug}.html yet) is
 * correctly absent and 404s until it actually publishes.
 *
 * Must be regenerated whenever public/ gains or loses a page, or
 * public/404.html's content changes — including every campaign article
 * publish (see lib/gitPublish.js, which regenerates and commits
 * functions/_validPaths.mjs as part of each publication commit).
 *
 * Usage: node scripts/generate-valid-paths.mjs
 */
import { readdirSync, statSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const PUBLIC = join(ROOT, 'public');

function walk(dir, results = []) {
  if (!existsSync(dir)) return results;
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) {
      if (name === 'admin') continue; // not a public content route
      walk(p, results);
    } else if (name.endsWith('.html')) {
      results.push(p);
    }
  }
  return results;
}

export function buildValidPaths() {
  const paths = new Set(['/']);
  const files = walk(PUBLIC);
  for (const file of files) {
    const rel = relative(PUBLIC, file).replace(/\\/g, '/');
    if (rel === 'index.html') continue; // already covered by '/'
    if (rel === '404.html') continue; // not a "real page" route
    if (rel.endsWith('/index.html')) {
      const dir = rel.slice(0, -'index.html'.length);
      paths.add(`/${dir}`); // e.g. stockton/ -> /stockton/
      paths.add(`/${dir}`.replace(/\/$/, '')); // and without trailing slash
    } else {
      paths.add(`/${rel}`); // e.g. /blog-sushi-etiquette.html
      paths.add(`/${rel.slice(0, -'.html'.length)}`); // and the clean-URL form
    }
  }
  return paths;
}

export function buildNotFoundPage() {
  return readFileSync(join(PUBLIC, '404.html'), 'utf8');
}

function main() {
  const paths = buildValidPaths();
  const sorted = [...paths].sort();
  const out = `/**\n * functions/_validPaths.mjs — GENERATED by scripts/generate-valid-paths.mjs.\n * Do not hand-edit; re-run the generator (or let build.mjs / the scheduler\n * publish step do it) after adding or publishing a page.\n */\nexport const VALID_PATHS = new Set(${JSON.stringify(sorted, null, 2)});\n`;
  const outPath = join(ROOT, 'functions', '_validPaths.mjs');
  writeFileSync(outPath, out);
  console.log(`[generate-valid-paths] Wrote ${sorted.length} paths to ${relative(ROOT, outPath)}`);

  const notFoundHtml = buildNotFoundPage();
  const notFoundOut = `/**\n * functions/_notFoundPage.mjs — GENERATED by scripts/generate-valid-paths.mjs\n * from public/404.html. Do not hand-edit; edit public/404.html and re-run\n * the generator instead. Inlined (rather than fetched via ASSETS at\n * request time) because context.env.ASSETS.fetch() cannot be trusted to\n * return a static file's real content from inside a Pages Function — see\n * the file header comment in this script for the live evidence.\n */\nexport const NOT_FOUND_HTML = ${JSON.stringify(notFoundHtml)};\n`;
  const notFoundOutPath = join(ROOT, 'functions', '_notFoundPage.mjs');
  writeFileSync(notFoundOutPath, notFoundOut);
  console.log(`[generate-valid-paths] Wrote 404 page body to ${relative(ROOT, notFoundOutPath)}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main();
}
